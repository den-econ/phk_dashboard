#!/usr/bin/env Rscript
# ============================================================================
# 05_export_results.R  —  build the result tables and stage them for the workbook
# ----------------------------------------------------------------------------
# Inputs : outputs/models.rds, outputs/lpi_composite.rds, outputs/lei_annual.rds
# Output : outputs/_xlsx_parts/*.csv   (each becomes a sheet in lpi_scores.xlsx
#          via 05b_build_xlsx.py). No standalone top-level CSVs — the workbook
#          is the single deliverable.
# Run from: model/model_LPI/  (after 03)
# ============================================================================
M  <- readRDS("outputs/models.rds")
M$L9$name <- "Indeks Kerentanan Pasar Kerja"          # match published report/dashboard
M$E5$name <- "Indeks Kerentanan Struktural Ekonomi"
LP <- readRDS("outputs/lpi_composite.rds"); res <- LP$res; W <- LP$W
ys <- as.character(2022:2025)

# tier label sets (G1 = highest score -> G3 = lowest); provinces split into 3 equal-count groups
LPI_LAB <- c("Risiko Tinggi","Risiko Sedang","Risiko Rendah")
PK_LAB  <- c("Pasar Kerja Berbasis Formal","Pasar Kerja dalam Transisi",
             "Pasar Kerja Informal Berbasis Pertanian")
ST_LAB  <- c("Ekonomi Industri Berorientasi Perdagangan","Ekonomi dengan Basis Industri Berkembang",
             "Ekonomi Domestik Berbasis Pertanian")
TM_LAB  <- c("Tekanan Tinggi","Tekanan Sedang","Tekanan Rendah")
tier_of <- function(s){ n<-length(s); rk<-rank(-s,ties.method="first")
  g<-ceiling(rk/(n/3)); g[g>3]<-3L; as.integer(g) }

## ---- headline scores table (province x year) -----------------------------
## per-pillar 3-tier labels within the year, plus avg LPI grouped by pillar tier
rows <- list()
for(yr in ys){ r<-res[[yr]]; pv<-names(r$s100)
  lpi<-as.numeric(r$s100); pk<-as.numeric(r$pk[pv]); st<-as.numeric(r$st[pv]); tk<-as.numeric(r$tk[pv])
  gL<-tier_of(lpi); gPKt<-tier_of(pk); gSTt<-tier_of(st); gTMt<-tier_of(tk)
  rows[[yr]] <- data.frame(
    year=as.integer(yr), province=pv,
    lpi_score         = round(lpi,1),
    pasar_kerja_score = round(pk,1),
    struktural_score  = round(st,1),
    tekanan_score     = round(tk,1),
    lpi_rank          = rank(-lpi,ties.method="first"),
    tier              = gL,
    lpi_tier_label         = LPI_LAB[gL],
    pasar_kerja_tier_label = PK_LAB[gPKt],
    struktural_tier_label  = ST_LAB[gSTt],
    tekanan_tier_label     = TM_LAB[gTMt],
    avg_lpi_tier_pasar_kerja = round(ave(lpi, gPKt, FUN=mean),1),  # mean LPI within labor category
    avg_lpi_tier_struktural  = round(ave(lpi, gSTt, FUN=mean),1),  # mean LPI within econ category
    row.names=NULL)
}
scores <- do.call(rbind, rows)
scores <- scores[order(scores$year, scores$lpi_rank), ]

## ---- pillar loadings (PC1) per pillar per year ----------------------------
loadrows <- list()
for(key in c("L9","E5")){ mod<-M[[key]]
  for(yr in ys){ e<-mod$E[[yr]]; ld<-e$load; ct<-100*ld^2/sum(ld^2)
    loadrows[[paste(key,yr)]] <- data.frame(
      index=mod$name, year=as.integer(yr),
      variable=mod$lab[names(ld)], pc1_loading=round(as.numeric(ld),3),
      contrib_pct=round(as.numeric(ct),1),
      msa=round(as.numeric(e$msa[names(ld)]),2), row.names=NULL) }}
loadings <- do.call(rbind, loadrows)

## ---- pillar metrics (KMO, PC1%, factors, cond#, Spearman vs PHK) ----------
metrows <- list()
for(key in c("L9","E5")){ mod<-M[[key]]
  for(yr in ys){ e<-mod$E[[yr]]
    metrows[[paste(key,yr)]] <- data.frame(
      index=mod$name, year=as.integer(yr), n=e$n,
      kmo=round(e$kmo,3), pc1_pct=round(100*e$pc1,0),
      factors_eig_gt1=sum(e$eig>1), cond_number=round(e$cond,0),
      spearman_phk_rate=round(e$sr,3), spearman_phk_total=round(e$st,3),
      row.names=NULL) }}
metrics <- do.call(rbind, metrows)

## ---- stage-2 worked example (2025): rotated loadings + weight build-up ----
r25<-res[["2025"]]; nm<-c(Labour="Kerentanan Pasar Kerja",Econ="Kerentanan Struktural Ekonomi",Pressure="Tekanan Makroekonomi")
s2 <- data.frame(index=nm[rownames(r25$Lr)],
  load_dim1=round(r25$Lr[,1],3), load_dim2=round(r25$Lr[,2],3),
  assigned_dim=c("Kerentanan","Tekanan")[r25$assign],
  within_share=round(mapply(function(i,f) r25$within[i,f], 1:3, r25$assign),3),
  dim_share=round(r25$fshare[r25$assign],3),
  weight_pct=round(100*r25$w,1), row.names=NULL)

## ---- metadata (README sheet) ----------------------------------------------
meta <- data.frame(field=c(
  "Product","Grain","Years","Method","Stage-1 pillars","Stage-2 weighting",
  "Aggregation","Columns","Scale","PHK role","Source (labour+econ)","Source (pressure)",
  "Generated by","Build date"),
  value=c(
  "Layoff Pressure Index (LPI) — provincial composite",
  "province-year (annual) + province-month (monthly sheet)",
  paste(range(as.integer(ys)),collapse="-"),
  "PCA pillars + OECD/JRC factor-analysis weighting (Handbook 2008, sec 6.1)",
  "Kerentanan Pasar Kerja (L9), Kerentanan Struktural Ekonomi (E5)",
  "2-factor varimax; weight = within-factor sq-loading share x factor variance share",
  "LPI = weighted sum of the three pillar scores (NOT re-normalised to 0-100)",
  "pasar_kerja/struktural/tekanan = pillar index scores; lpi = their weighted sum; use `lpi`",
  "all scores 0-100: pillars are min-max across provinces (structure within the year, tekanan within each month); lpi is their weighted sum (also 0-100)",
  "validation target only — never an input",
  "data/clean/phk_master.csv (via model_LPI pillar PCA)",
  "model_LEI/data/Komposit_LEI_Ketenagakerjaan.xlsx (LEI Per Provinsi)",
  "model/model_LPI/code/ (00-08)", as.character(Sys.Date())))

## ---- stage every table as a workbook part (05b packages these) ------------
dir.create("outputs/_xlsx_parts", showWarnings=FALSE)
write.csv(meta,     "outputs/_xlsx_parts/00_README.csv",          row.names=FALSE)
write.csv(scores,   "outputs/_xlsx_parts/01_scores.csv",          row.names=FALSE)
write.csv(W,        "outputs/_xlsx_parts/02_weights.csv",         row.names=FALSE)
write.csv(metrics,  "outputs/_xlsx_parts/03_pillar_metrics.csv",  row.names=FALSE)
write.csv(loadings, "outputs/_xlsx_parts/04_pillar_loadings.csv", row.names=FALSE)
write.csv(s2,       "outputs/_xlsx_parts/05_stage2_2025.csv",     row.names=FALSE)
cat(sprintf("staged parts: %d score rows, %d loading rows, %d metric rows\n",
            nrow(scores), nrow(loadings), nrow(metrics)))
