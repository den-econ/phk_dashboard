#!/usr/bin/env Rscript
# ============================================================================
# 05_export_results.R  —  canonical LPI result tables (CSV parts for the workbook)
# ----------------------------------------------------------------------------
# Inputs : outputs/models.rds, outputs/lpi_composite.rds, outputs/lei_annual.rds
# Outputs: outputs/lpi_scores_long.csv        (headline: province-year scores + tier)
#          outputs/pillar_loadings.csv
#          outputs/pillar_metrics.csv
#          outputs/stage2_2025.csv
#          outputs/lpi_weights_by_year.csv     (re-exported for the workbook)
#          outputs/_xlsx_parts/*.csv           (fed to 05b_build_xlsx.py)
# The Excel workbook lpi_scores.xlsx is assembled from these by 05b_build_xlsx.py.
# Run from: model/model_LPI/  (after 03)
# ============================================================================
M  <- readRDS("outputs/models.rds")
M$L9$name <- "Indeks Kerentanan Pasar Kerja"          # match published report/dashboard
M$E5$name <- "Indeks Kerentanan Struktural Ekonomi"
LP <- readRDS("outputs/lpi_composite.rds"); res <- LP$res; W <- LP$W
agg<- readRDS("outputs/lei_annual.rds")$agg
ys <- as.character(2022:2025)

TIER_LAB <- c("Risiko Sangat Tinggi","Risiko Tinggi","Risiko Sedang","Risiko Rendah") # G1 highest
tier_of <- function(s){ n<-length(s); rk<-rank(-s,ties.method="first")
  g<-ceiling(rk/(n/4)); g[g>4]<-4L; as.integer(g) }
mm01 <- function(x) 100*(x-min(x))/(max(x)-min(x))   # min-max 0-100

## ---- headline scores table (province x year) -----------------------------
rows <- list()
for(yr in ys){ r<-res[[yr]]; pv<-names(r$s100)
  pk <- M$L9$E[[yr]]$s100[pv]                       # Kerentanan Pasar Kerja (0-100)
  st <- M$E5$E[[yr]]$s100[pv]                       # Kerentanan Struktural  (0-100)
  lv <- setNames(agg$Indeks_LEI_Labour[agg$Tahun==as.integer(yr)],
                 agg$Provinsi[agg$Tahun==as.integer(yr)])[pv]
  tk <- mm01(lv)                                    # Tekanan Makroekonomi (0-100, within LPI sample)
  g  <- tier_of(r$s100)
  rows[[yr]] <- data.frame(
    year=as.integer(yr), province=pv,
    pasar_kerja_0_100 = round(as.numeric(pk),1),
    struktural_0_100  = round(as.numeric(st),1),
    tekanan_0_100     = round(as.numeric(tk),1),
    lpi_0_100         = round(as.numeric(r$s100),1),
    lpi_raw           = round(as.numeric(r$raw[pv]),3),
    lpi_rank          = rank(-r$s100,ties.method="first"),
    tier              = g,
    tier_label        = TIER_LAB[g],
    row.names=NULL)
}
scores <- do.call(rbind, rows)
scores <- scores[order(scores$year, scores$lpi_rank), ]
write.csv(scores, "outputs/lpi_scores_long.csv", row.names=FALSE)

## ---- pillar loadings (PC1) per pillar per year ----------------------------
loadrows <- list()
for(key in c("L9","E5")){ mod<-M[[key]]
  for(yr in ys){ e<-mod$E[[yr]]; ld<-e$load; ct<-100*ld^2/sum(ld^2)
    loadrows[[paste(key,yr)]] <- data.frame(
      index=mod$name, year=as.integer(yr),
      variable=mod$lab[names(ld)], pc1_loading=round(as.numeric(ld),3),
      contrib_pct=round(as.numeric(ct),1),
      msa=round(as.numeric(e$msa[names(ld)]),2), row.names=NULL) }}
loadings <- do.call(rbind, loadrows)
write.csv(loadings, "outputs/pillar_loadings.csv", row.names=FALSE)

## ---- pillar metrics (KMO, PC1%, factors, cond#, Spearman vs PHK) ----------
metrows <- list()
for(key in c("L9","E5")){ mod<-M[[key]]
  for(yr in ys){ e<-mod$E[[yr]]
    metrows[[paste(key,yr)]] <- data.frame(
      index=mod$name, year=as.integer(yr), n=e$n,
      kmo=round(e$kmo,3), pc1_pct=round(100*e$pc1,0),
      factors_eig_gt1=sum(e$eig>1), cond_number=round(e$cond,0),
      spearman_phk_rate=round(e$sr,3), spearman_phk_total=round(e$st,3),
      row.names=NULL) }}
metrics <- do.call(rbind, metrows)
write.csv(metrics, "outputs/pillar_metrics.csv", row.names=FALSE)

## ---- stage-2 worked example (2025): rotated loadings + weight build-up ----
r25<-res[["2025"]]; nm<-c(Labour="Kerentanan Pasar Kerja",Econ="Kerentanan Struktural Ekonomi",Pressure="Tekanan Makroekonomi")
s2 <- data.frame(index=nm[rownames(r25$Lr)],
  load_dim1=round(r25$Lr[,1],3), load_dim2=round(r25$Lr[,2],3),
  assigned_dim=c("Kerentanan","Tekanan")[r25$assign],
  within_share=round(mapply(function(i,f) r25$within[i,f], 1:3, r25$assign),3),
  dim_share=round(r25$fshare[r25$assign],3),
  weight_pct=round(100*r25$w,1), row.names=NULL)
write.csv(s2, "outputs/stage2_2025.csv", row.names=FALSE)

## ---- metadata (README sheet) ----------------------------------------------
meta <- data.frame(field=c(
  "Product","Grain","Years","Method","Stage-1 pillars","Stage-2 weighting",
  "Composite scaling","PHK role","Source (labour+econ)","Source (pressure)",
  "Generated by","Build date"),
  value=c(
  "Layoff Pressure Index (LPI) — provincial composite",
  "province-year", paste(range(as.integer(ys)),collapse="-"),
  "PCA pillars + OECD/JRC factor-analysis weighting (Handbook 2008, sec 6.1)",
  "Kerentanan Pasar Kerja (L9), Kerentanan Struktural Ekonomi (E5)",
  "2-factor varimax; weight = within-factor sq-loading share x factor variance share",
  "weighted sum of standardised pillars, min-max 0-100 within each year",
  "validation target only — never an input",
  "data/clean/phk_master.csv (via model_LPI pillar PCA)",
  "model_LEI/data/Komposit_LEI_Ketenagakerjaan.xlsx (LEI Per Provinsi, annual mean)",
  "model/model_LPI/code/ (01-06)", as.character(Sys.Date())))
write.csv(meta, "outputs/_meta.csv", row.names=FALSE)

## ---- stage the parts for the workbook builder -----------------------------
dir.create("outputs/_xlsx_parts", showWarnings=FALSE)
file.copy(c("outputs/_meta.csv","outputs/lpi_scores_long.csv","outputs/lpi_weights_by_year.csv",
            "outputs/pillar_metrics.csv","outputs/pillar_loadings.csv","outputs/stage2_2025.csv"),
          c("outputs/_xlsx_parts/00_README.csv","outputs/_xlsx_parts/01_scores.csv",
            "outputs/_xlsx_parts/02_weights.csv","outputs/_xlsx_parts/03_pillar_metrics.csv",
            "outputs/_xlsx_parts/04_pillar_loadings.csv","outputs/_xlsx_parts/05_stage2_2025.csv"),
          overwrite=TRUE)
cat(sprintf("exported: %d score rows, %d loading rows, %d metric rows\n",
            nrow(scores), nrow(loadings), nrow(metrics)))
